/**
 * سياسةُ الاعتماد — **قرار المالك ٢/٩/٢٦**، ومصدرُ الحقيقة الوحيد لمن يعتمد ومتى.
 *
 * ## القاعدة
 *
 *   شخصان لا أكثر:
 *     • **الموظّف** ينفّذ العملية **كاملةً** — ينشئ ويعدّل ويستلم ويطابق ويجهّز.
 *       لا أحد يقاطعه في المنتصف.
 *     • **المالك حصراً** يعتمد **مرّةً واحدة في الخاتمة**. ولا اعتمادَ بعده —
 *       لا مديرَ فرعٍ ولا محاسب.
 *     • **وإذا نفّذ المالك بنفسه ⇒ يُعتمَد تلقائياً** ويُسجَّل أنّه اعتمد نفسَه.
 *
 * ## وتنفتح البوّابة في حالتين فقط
 *
 *   `MONEY_OUT`     خروجُ مالٍ من الشركة — دفعُ مورّد · ردٌّ لعميل · صرفُ مصروف ·
 *                   دفعُ أجرة مندوب · سحبٌ من محفظة · شطبُ ذمّة.
 *   `ERASE_EFFECT`  محوُ أثرٍ ماليٍّ أو مخزنيٍّ **قائم** — إلغاءُ مستندٍ ذي قيد ·
 *                   عكسُ استلام · تسويةُ مخزونٍ بالنقص · مسُّ فترةٍ مُقفَلة ·
 *                   إعادةُ تقييم تكلفةٍ لصنفٍ له رصيد.
 *
 * **وما عداهما يُنفَّذ فوراً ويُسجَّل.** لا اعتماد على إنشاءٍ ولا إرسالٍ ولا استلامٍ ولا
 * مطابقةٍ ولا ترحيلِ فاتورةٍ ولا أيّ خطوةٍ وسيطة.
 *
 * ## لماذا هذه الصيغة صحيحةٌ رقابياً لا تنازلاً
 *
 * الفصلُ القائم اليوم يوزّع الشراء على **٣ إلى ٥ مستخدمين متمايزين** (منشئ ≠ معتمد ≠
 * مستلم ≠ مطابق ≠ دافعٌ بصلاحية خزينة)، فيوقف العمل يومياً في محلٍّ بفرعين ولا يضيف
 * حمايةً تُذكَر: تفتيتُ **العمل** على خمسةٍ ليس حمايةً — الحمايةُ **عينٌ مستقلّة على لحظة
 * الالتزام**. وموظّفٌ يسجّل استلاماً وهمياً يُنتج ذمّةً لا نقداً، ويُحاصَر عند الدفع؛
 * ومخزوناً وهمياً يكشفه الجرد. فالبوّابة الواحدة عند خروج المال ومحو الأثر تمسك ما يؤذي.
 *
 * ⚠️ **والتقريرُ يحلّ محلّ الفصل، فهو جزءٌ من السياسة لا زينةٌ بعدها:** كلُّ ما نفّذه
 * موظّفٌ وحده — وكلُّ ما اعتمده المالك على نفسه — يجب أن يظهر في شاشةٍ واحدة مرتّبةٍ
 * بالمبلغ. بلا هذه الشاشة تصير القاعدة تبسيطاً **بلا** رقابة.
 *
 * ## فائدةٌ بنيوية جانبية: القاعدة تفكّ جموداً مضموناً
 *
 * الفحصُ القائم يمنع المنشئ من اعتماد نفسه **بلا استثناءٍ للمالك في المشتريات وضبط
 * المبيعات والإجازات والمصروفات** — فإذا أنشأ المالك مستنداً بنفسه لم يبقَ مَن يعتمده،
 * إذ لا أحدَ فوقه. ومن هنا كان الاستثناء **متبايناً عمداً** بين الوحدات (بعضها يستثني
 * الأدمن وبعضها لا). هذه القاعدة تُنهي التباين بجوابٍ واحد.
 */

/** لحظةُ الخطر التي تفتح البوّابة. لا ثالثَ لهما. */
export type ApprovalTrigger = "MONEY_OUT" | "ERASE_EFFECT";

export const APPROVAL_TRIGGERS = ["MONEY_OUT", "ERASE_EFFECT"] as const;

export const APPROVAL_TRIGGER_LABEL_AR: Record<ApprovalTrigger, string> = {
  MONEY_OUT: "خروج مال",
  ERASE_EFFECT: "محو أثر قائم",
};

/** ما الذي يجب أن يحدث الآن. */
export type ApprovalOutcome =
  /** لا بوّابة — يُنفَّذ فوراً ويُسجَّل. */
  | "NOT_REQUIRED"
  /** المالك هو المنفّذ ⇒ اعتمادٌ تلقائيّ، ولا اعتمادَ بعده. */
  | "AUTO_SELF_APPROVED"
  /** يلزم اعتمادُ المالك قبل الأثر. */
  | "NEEDS_OWNER";

export interface ApprovalDecision {
  outcome: ApprovalOutcome;
  /** نصٌّ عربيٌّ يُعرَض للمستخدم ويُكتب في أثر التدقيق. لا قرارَ بلا سببٍ مقروء. */
  reason: string;
  /** هل يُسجَّل هذا الفعل في تقرير «نُفِّذ بشخصٍ واحد»؟ */
  soloExecution: boolean;
}

export interface ApprovalInput {
  /**
   * لحظةُ الخطر إن وُجدت. `null` تعني أنّ العملية لا تُخرج مالاً ولا تمحو أثراً —
   * وهي **الغالبية العظمى** من عمليات النظام.
   */
  trigger: ApprovalTrigger | null;
  /** هل المنفّذ هو المالك؟ (`users.isOwner`) */
  actorIsOwner: boolean;
}

/**
 * القرار الوحيد. ثلاثةُ فروعٍ لا رابع لها — وهذا هو التبسيط المطلوب حرفياً.
 *
 * ⛔ لا تُضِف فرعاً هنا بحجّة حالةٍ خاصّة. كل «حالةٍ خاصّة» أُضيفت إلى سياسة اعتمادٍ في
 * هذا المستودع صارت لاحقاً بوّابةً لا أحد يعرف لماذا هي موجودة. إن لزم استثناءٌ فليكن
 * في **تصنيف اللحظة** (هل هذه العملية `MONEY_OUT` أصلاً؟) لا في قرار الاعتماد.
 */
export function resolveApproval(input: ApprovalInput): ApprovalDecision {
  if (input.trigger === null) {
    return {
      outcome: "NOT_REQUIRED",
      reason: "لا خروجَ مالٍ ولا محوَ أثر — يُنفَّذ فوراً ويُسجَّل.",
      soloExecution: true,
    };
  }
  const what = APPROVAL_TRIGGER_LABEL_AR[input.trigger];
  if (input.actorIsOwner) {
    return {
      outcome: "AUTO_SELF_APPROVED",
      reason: `${what} — نفّذه المالك، فاعتُمد تلقائياً (لا اعتمادَ بعده).`,
      soloExecution: true,
    };
  }
  return {
    outcome: "NEEDS_OWNER",
    reason: `${what} — يلزم اعتمادُ المالك قبل التنفيذ.`,
    soloExecution: false,
  };
}

/** هل ينفَّذ الفعل الآن؟ (`NOT_REQUIRED` أو اعتمادُ المالك لنفسه). */
export function executesNow(decision: ApprovalDecision): boolean {
  return decision.outcome !== "NEEDS_OWNER";
}

/**
 * رسالةُ الحجب حين يلزم اعتمادُ المالك — بالأجزاء الأربعة (ماذا · لماذا · ماذا تفعل).
 * تُبنى هنا لا في كل خدمة، وإلّا صارت خمسين صياغةً لمعنًى واحد.
 */
export function ownerApprovalRequiredMessage(args: {
  trigger: ApprovalTrigger;
  /** وصفٌ قصيرٌ للمستند: «أمر شراء PO-1024» · «مصروف ٢٥٠٬٠٠٠». */
  subject: string;
}): string {
  const what = APPROVAL_TRIGGER_LABEL_AR[args.trigger];
  return (
    `${args.subject}: هذا الإجراء فيه ${what}، ويلزمه اعتماد المالك. ` +
    `أُرسِل الطلب — يظهر عند المالك في «مطلوب مني الآن» ويُنفَّذ فور اعتماده.`
  );
}

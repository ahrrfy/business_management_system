/**
 * سياسة **سعر القائمة الإلزاميّ** — قرار المالك ١٨/٨/٢٦، البند H7 من تدقيق ٢٧/٧.
 *
 * البند كما رصده التدقيق: «بندٌ تكلفته صفر يُباع بأيّ سعرٍ حتى الصفر بلا اعتماد». وجذرُه أعمق
 * ممّا وصفه التقرير: بوّابتا الانحراف (H6) تقيسان **نسبة** التنازل عن مرجعٍ، فإن لم يكن للبند
 * مرجعٌ موجب فالمقام صفرٌ ⇒ `refGross.lte(0) ⇒ return false` في كلتيهما، وبوّابةُ تحت-التكلفة
 * لا تنطلق عند `costPrice = 0`. فالبندُ بلا سعر قائمةٍ **بلا حارسٍ إطلاقاً**: يُباع بألف أو
 * بواحدٍ أو بصفر، بلا اعتمادٍ ولا وسمِ تدقيق.
 *
 * **الخياران اللذان عُرِضا على المالك:** (أ) إلزام سعر قائمةٍ لكل صنفٍ يُباع، أو (ب) اعتبار
 * «البند بلا مرجع» موجِباً لموافقة مدير. **اختار المالك (أ)** — فهي تُصلح المنبع لا العَرَض:
 * الموافقة كانت ستُطالَب بها عند كل بيعةٍ لبندٍ ناقص البيانات، فتصير طقساً يُوقَّع بلا قراءة.
 *
 * **القاعدة:** لا يُباع بندٌ إلا بمرجعٍ **موجب** — عقدُ عميلٍ، أو سعرُ قائمةٍ لفئته، أو مرجعٌ
 * تفرضه الخدمة من مصدرٍ مقفولٍ في القاعدة (البطاقات الرقمية). والصفرُ **ليس** مرجعاً: صفٌّ
 * بسعر `0.00` لا يختلف عن غيابه أمام القسمة، وهو ما تُنشئه البطاقاتُ الرقمية عمداً كعنصرٍ
 * نائب (`offeringService`: «real price comes from digital pricing») — فيلزمها المرجع الصريح.
 *
 * ⚠️ **الحدّ:** هذه السياسة تُلزِم بوجود المرجع لا بمقداره. التسعيرُ فوق/تحت المرجع يبقى
 * محكوماً بعتبة H6 (`MANUAL_DISCOUNT_APPROVAL_THRESHOLD`) — وهي الآن **تعمل فعلاً** لأنّ
 * المقام صار موجباً حتماً.
 */

/** فئات السعر — مطابقةٌ لـ`PriceTier` في الخادم (مكرَّرةٌ هنا كي يبقى `shared` بلا تبعية). */
export type ListPriceTier = "RETAIL" | "WHOLESALE" | "GOVERNMENT";

/** التسمية العربية للفئة — تُستعمَل في رسائل الرفض وفي الشاشات (قاموسٌ واحد لا سبعة). */
export const PRICE_TIER_LABEL_AR: Record<ListPriceTier, string> = {
  RETAIL: "مفرد",
  WHOLESALE: "جملة",
  GOVERNMENT: "حكومي",
};

/**
 * هل النصّ سعرٌ **موجب**؟ فحصٌ نصّيّ بحت بلا `Number`/`parseFloat` (قاعدة §٥: لا تحويل عدديّ
 * على الأموال) — يقبل `"1"` و`"0.01"` و`"1450.99"`، ويرفض `""` و`"0"` و`"0.00"` و`"abc"`
 * والسالب. المعيار: نصٌّ عشريٌّ غير سالب فيه **خانةٌ واحدة على الأقلّ غير صفر**.
 */
export function isPositivePriceString(raw: string | null | undefined): boolean {
  if (raw == null) return false;
  const t = String(raw).trim();
  if (!/^\d+(\.\d+)?$/.test(t)) return false;
  return /[1-9]/.test(t);
}

/** وسمُ مصدر المرجع — يظهر في رسالة الرفض كي يعرف الموظّف **أين** يُصلح. */
export type ListPriceRefSource = "CONTRACT" | "LIST" | "SERVICE";

/**
 * رسالةُ رفضٍ **قابلةٌ للتنفيذ**: تسمّي البند والوحدة والفئة، وتقول أين يُضبط السعر بالضبط.
 * رسالةٌ عمياء («لا يوجد سعر») تُوقِف الكاشير أمام الزبون بلا مخرج — وهو ما جعل ضابط مطابقة
 * فاتورة المورّد يُعطَّل كلّياً قبل #640، فلا نُكرّر الخطأ.
 */
export function missingListPriceMessage(o: {
  itemLabel: string;
  unitLabel?: string | null;
  tier: ListPriceTier;
}): string {
  const unit = o.unitLabel ? ` (وحدة: ${o.unitLabel})` : "";
  return (
    `لا يُباع «${o.itemLabel}»${unit} بلا سعر قائمة لفئة «${PRICE_TIER_LABEL_AR[o.tier]}». ` +
    `اضبط السعر من: المنتجات ← تعديل الصنف ← الوحدات والأسعار، ثمّ أعد المحاولة. ` +
    `(سياسة المالك: كل صنفٍ يُباع له سعر قائمةٍ موجب — به وحده يُقاس أيّ خصمٍ أو تنازل.)`
  );
}

/** رسالةُ منع الحفظ في محرّر المنتج — الإلزام عند المنبع، في لحظةٍ هادئة لا أمام الزبون. */
export function baseUnitPriceRequiredMessage(o: { variantLabel: string; unitLabel: string }): string {
  return (
    `الصنف «${o.variantLabel}» لا يُحفَظ بلا سعر مفرد للوحدة الأساس «${o.unitLabel}». ` +
    `سياسة المالك: كل صنفٍ يُباع له سعر قائمةٍ موجب. ` +
    `إن كان الصنف للشراء فقط ولا يُباع، فعطّله أو أبقِه بلا وحدة بيع.`
  );
}

/**
 * deliveryTerminology — قاموس المصطلحات المُوحَّد لمنظومة التوصيل (Slice DFP2، ٣١/٨/٢٦).
 *
 * السبب (الفحص البصريّ ٣١/٨): ٧ شاشات تسمّي نفس المفهوم بأسماءٍ مختلفة:
 *   - «بذمّتها» و«العهدة» و«التعرّض» و«الذمّة» ⇒ ٤ ألفاظ لمفهومٍ واحد.
 *   - «طرود مفتوحة» تعني ٣ أشياء مختلفة بحسب الشاشة (٥ vs ٥١ vs ٧).
 *   - «حدّد» / «مُحدَّد» / «قيد التحصيل» زرٌّ واحد بثلاثة أسماء.
 * كل شاشة تنجرف بمعناها ⇒ الكاشير يفهم نصف كلمة.
 *
 * القاعدة السارية بعد DFP2:
 *   ⛔ لا نصّ عربيّ محلّيّ في شاشات التوصيل — كلّ لفظٍ من هذا القاموس.
 *   ⛔ لا تشكيل (فتحة/ضمّة/كسرة/شدّة) في الشارات والرؤوس بحجم < 14px:
 *      خطّ الواجهة (Cairo/Tajawal افتراضياً) يرسم «مُ + كلمة» كأنها «ف + كلمة» في الحجم الصغير.
 *      حلٌّ عمليّ: تقديم نسختين لكل مصطلح (compact بلا تشكيل + prose بتشكيل كامل).
 *
 * البنيةٌ:
 *   TERM = { compact: "بلا تشكيل"، prose: "بتشكيلٍ كامل"، tooltip: "شرحٌ للـtitle" }
 */


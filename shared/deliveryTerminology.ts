export type DeliveryTermKey = keyof typeof DELIVERY_TERMS;

/** إرجاع النسخة المدمجة (compact) لمصطلحٍ — للاستعمال في شارةٍ أو رأس عمود. */
export function termCompact(key: DeliveryTermKey): string {
  return DELIVERY_TERMS[key].compact;
}

/** إرجاع النسخة الأدبيّة (prose) لمصطلحٍ — للاستعمال في عنوانٍ أو فقرة. */
export function termProse(key: DeliveryTermKey): string {
  return DELIVERY_TERMS[key].prose;
}

/** إرجاع الشرح (tooltip) لمصطلحٍ — للاستعمال في title attribute. */
export function termTooltip(key: DeliveryTermKey): string {
  return DELIVERY_TERMS[key].tooltip;
}

/**
 * كائنٌ جاهز للاستعمال في header جدول:
 *   <th title={t.tooltip}>{t.compact}</th>
 * أو في شارة:
 *   <Badge title={t.tooltip}>{t.compact}</Badge>
 */
export function term(key: DeliveryTermKey): DeliveryTerm {
  return DELIVERY_TERMS[key];
}

/**
 * عقد رسالة الخطأ — **مصدر الحقيقة الوحيد** لبناء رسالةٍ عربيةٍ يستطيع الموظّف التصرّف بها.
 *
 * **قرار المالك:** الرسالة أربعة أجزاء لا اثنان:
 *
 *   ① `what`   — **ماذا حدث** (الحدث كما يراه الموظّف، لا كما يراه الكود).
 *   ② `why`    — **لماذا** (السبب، وفيه الأرقام إن كان الرفض رقمياً).
 *   ③ `doThis` — **ماذا تفعل الآن** (المخرج العمليّ: بديلٌ أو خطوةٌ أو جهةٌ تُطلَب منها).
 *   ④ `action` — **زرٌّ يفعلها** (اختياريّ: تسميةٌ ووجهةٌ داخل النظام).
 *
 * **الجذر:** أغلب رسائل النظام اليوم تقول ① و② وتقف، فيقف الموظّف معها. أسوأ مثالٍ حيّ
 * «GRNI الحالي يدعم سياسة الضريبة العراقية الصفرية فقط» ([`goodsReceipts.ts`](../server/services/purchase/goodsReceipts.ts)):
 * البضاعة على الرصيف، والرسالة صحيحةٌ تماماً ولا تقول ماذا يفعل السائق المنتظر. وأفضلُ مثالٍ
 * حيّ هو حارس مطابقة فاتورة المورّد ([`purchase/order.ts`](../server/services/purchase/order.ts)):
 * الرقمان والفرق واتّجاهه وسببه المعتاد — وهو المعيار الذي يُقاس عليه هذا العقد.
 *
 * **لماذا `doThis` إلزاميّ في النوع وفي وقت التشغيل معاً:** هو الجزءُ الذي يُنسى دائماً — كاتب
 * الحارس يعرف السبب فيكتبه ويظنّ أنّه أدّى ما عليه. جعلُه إلزامياً في النوع يمنع النسيان عند
 * التأليف، والفحصُ في وقت التشغيل يمنعه من مستدعٍ غير مُنمَّط (استيراد/بذرة/جافاسكربت) — نفس
 * منطق «الدفاع المتعمّق» في خدمات الشراء.
 *
 * **لماذا `action` اختياريّ وحده:** الناقل اليوم نصٌّ واحد (`TRPCError.message`) لا يحمل بنيةً،
 * فالزرّ لا يعبر إلّا حيث تبني الشاشةُ الرسالةَ بنفسها. ولذلك **يجب أن يقف `doThis` وحده**:
 * هو المخرج المكتوب الذي ينجو دائماً، والزرّ اختصارٌ له لا بديلٌ عنه.
 *
 * ملاحظة موقع: `shared/` كي يبنيه الخادم في حرّاسه وتبنيه الشاشة في حجبها الاستباقيّ بالصيغة
 * نفسها — فلا ينجرف نصّان لمعنًى واحد كما انجرفت قواميس حالة الفاتورة قبل توحيدها.
 */

/** زرٌّ ينفّذ `doThis`. `href` مسارٌ **داخل النظام** (يبدأ بـ`/`) كي يفتحه wouter لا المتصفّح. */
export type AppErrorAction = {
  /** تسمية الزرّ العربية — فعلُ أمرٍ قصير («افتح وردية»، «أنشئ مرتجع شراء»). */
  label: string;
  /** وجهة داخل التطبيق. غيابُها = زرٌّ يتولّاه المستدعي (فتح مودال مثلاً) لا تنقّلٌ. */
  href?: string;
};

/** أجزاء العقد كما يكتبها المؤلّف. `doThis` **إلزاميّ** — انظر شرح الرأس. */
export type AppErrorParts = {
  /** ① ماذا حدث. */
  what: string;
  /** ② لماذا — ضع هنا الأرقام والفرق واتّجاهه إن كان الرفض رقمياً. */
  why: string;
  /** ③ ماذا تفعل الآن — مخرجٌ عمليّ، لا إعادةُ صياغةٍ للسبب. */
  doThis: string;
  /** ④ زرٌّ يفعلها (اختياريّ). */
  action?: AppErrorAction;
};

/** النتيجة: الأجزاء كما هي (للشاشة) + `message` نصّاً واحداً (للناقل النصّيّ). */
export type AppError = {
  what: string;
  why: string;
  doThis: string;
  action?: AppErrorAction;
  /** الرسالة العربية المركَّبة: «ماذا — لماذا. ماذا تفعل». سطرٌ واحد دائماً. */
  message: string;
};

/**
 * فاصل ① عن ②: الشرطة المُعترِضة هي فاصلُ «الحدث ثمّ سببه» المستعمل في المستودع أصلاً
 * («الأمر مُسلَّم وصدرت فاتورته — عالِج الفرق…»). تثبيتُه هنا يمنع انجراف الشكل بين الحرّاس.
 */
const WHAT_WHY_SEPARATOR = " — ";

/** أرقام هندية (٠-٩) — ممنوعة بقرار المالك: كلّ رقمٍ يعرضه النظام لاتينيّ. */
// (الفئات مكتوبةٌ بترميز يونيكود لا بحروفٍ عربية: المحارف العربية داخل التعابير النمطية
//  تنكسر على أدوات التحرير ثنائية الاتجاه — علّةٌ موثَّقة في المستودع.)
const ARABIC_INDIC_DIGITS_G = /[\u0660-\u0669\u06F0-\u06F9]/g;

/** علامات نهايةٍ مقبولة — لا نُلحق نقطةً بجملةٍ منتهيةٍ أصلاً. */
const TERMINAL_PUNCTUATION = /[.!?:\u061F\u2026]$/;

/**
 * تسويةُ جزء: قصُّ الأطراف وطيُّ كلّ فراغٍ متتابع (بما فيه أسطرُ القوالب النصّية) إلى مسافةٍ
 * واحدة. بلا هذا تُنتج قوالبُ `\n` داخل الرسالة، فتنكسر في التوست وفي سطر الجدول معاً.
 */
function normalizePart(raw: string): string {
  return String(raw).replace(/\s+/g, " ").trim();
}

/** إسقاط نقطةٍ/فاصلةٍ ختامية قبل الوصل — الفاصلُ يتكفّل بالفصل، فلا تجتمع علامتان. */
function stripTrailingSeparator(part: string): string {
  return part.replace(/[.,;\u060C\u061B]+$/, "").trim();
}

/**
 * خريطةُ الأرقام الهندية إلى اللاتينية — **تطبيعٌ لا رمي**.
 *
 * ⚠️ الرميُ هنا كان عطباً حقيقياً: هذه الدالّة تعمل **داخل مسار بناء رسالة الرفض**، وأجزاؤها
 * تُستوفى من بيانات المستخدم (اسمُ مورّدٍ أو منتجٍ أو ملاحظةٌ قد تُكتب بأرقام هندية). فمورّدٌ
 * اسمه «مكتبة ١٢٣» كان يقلب رفضاً عملياً نظيفاً (FORBIDDEN) إلى **500 ويُضيّع سببَ الرفض
 * الأصليّ** — نقيضُ غرض هذا الملفّ حرفياً. القاعدة تبقى مفروضة، لكن بالتصحيح لا بالإسقاط.
 */
const ARABIC_INDIC_TO_LATIN: Record<string, string> = {
  "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
  "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
  "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
  "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
};

/** يُحوّل كلّ رقمٍ هنديّ إلى نظيره اللاتينيّ (قرار المالك: الأرقام لاتينية دائماً). */
export function toLatinDigits(text: string): string {
  return text.replace(ARABIC_INDIC_DIGITS_G, (d) => ARABIC_INDIC_TO_LATIN[d] ?? d);
}

function assertPresent(value: string, fieldLabel: string): string {
  // ⚠️ الترتيب مقصود: **طبِّع ثمّ اقصّ ثمّ افحص الفراغ**. الفحصُ قبل قصّ الفواصل كان يُمرّر
  // جزءاً يصير فارغاً بعده — `why: "."` كان ينتج «تعذّر — . افعل.» رغم وعد «بلا تسامح».
  const normalized = stripTrailingSeparator(toLatinDigits(normalizePart(value ?? "")));
  if (normalized === "") {
    throw new Error(`appError: الجزء «${fieldLabel}» مطلوب ولا يصحّ أن يكون فارغاً`);
  }
  return normalized;
}

/**
 * بناء رسالة الخطأ من أجزائها الأربعة.
 *
 * يرفض — بلا تسامح — أربعَ حالاتٍ كلٌّ منها أنتج رسالةً ميتةً في المستودع فعلاً:
 *   • جزءٌ نصّيٌّ فارغ (وأخصّها `doThis`: «① و② ثمّ وقوف»).
 *   • أرقامٌ هندية (قرار المالك: الأرقام لاتينية دائماً).
 *   • `doThis` نسخةٌ من `why` — إعادةُ صياغة السبب ليست مخرجاً.
 *   • `action.href` خارجيّ أو غير مسار — زرُّ الخطأ ينقل داخل النظام لا إلى الإنترنت.
 */
export function appError(parts: AppErrorParts): AppError {
  const what = assertPresent(parts.what, "ماذا حدث");
  const why = assertPresent(parts.why, "لماذا");
  const doThis = assertPresent(parts.doThis, "ماذا تفعل الآن");

  // «لماذا» مُعادةً بصياغةٍ أخرى ليست مخرجاً: الموظّف يقرأ السبب مرّتين ويبقى واقفاً.
  if (doThis === why) {
    throw new Error("appError: «ماذا تفعل الآن» يكرّر «لماذا» — الرسالة بلا مخرجٍ عمليّ");
  }

  let action: AppErrorAction | undefined;
  if (parts.action) {
    const label = assertPresent(parts.action.label, "تسمية الزرّ");
    const href = parts.action.href == null ? undefined : normalizePart(parts.action.href);
    // ⚠️ `startsWith("/")` وحدها **لا تكفي**: المسار البروتوكول-نسبيّ `//evil.com` يبدأ
    // بشرطةٍ مائلة ويقود إلى الإنترنت — وكذلك `/\evil.com` في بعض المتصفّحات. زرُّ رسالة
    // خطأٍ يجب أن ينقل داخل النظام حصراً.
    if (href !== undefined && (!href.startsWith("/") || /^\/[/\\]/.test(href))) {
      throw new Error(
        `appError: وجهة الزرّ «${href}» ليست مساراً داخل النظام — يجب أن تبدأ بـ«/» ولا تتبعها «/» أو «\»`,
      );
    }
    action = href === undefined ? { label } : { label, href };
  }

  const tail = TERMINAL_PUNCTUATION.test(doThis) ? doThis : `${doThis}.`;
  const message = `${what}${WHAT_WHY_SEPARATOR}${why}. ${tail}`;

  return action ? { what, why, doThis, action, message } : { what, why, doThis, message };
}

/**
 * اختصارٌ لمواضع الرمي: `throw new TRPCError({ code, message: appErrorMessage({ … }) })`.
 *
 * ⚠️ الناقل نصٌّ فقط ⇒ `action` **لا يعبر** من هنا. استعمله حيث يكفي `doThis` مكتوباً، واحتفظ
 * بـ`appError` كاملاً حيث تملك الشاشة بنيةَ الرسالة (الحجب الاستباقيّ، الحالات الفارغة).
 */
export function appErrorMessage(parts: AppErrorParts): string {
  return appError(parts).message;
}

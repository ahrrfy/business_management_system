/** المفتاحُ صالحٌ للاستهلاك في الشاشات. */
export type TermKey = keyof typeof TERMS;

/**
 * ⭐ **الدالّةُ المساعدة**: احصل على المصطلح بأمانٍ من TypeScript (خطأ نوعٍ لو أخطأتَ المفتاح).
 *
 * @example
 *   term("unpaidInvoice").compact   // "غير مدفوعة"
 *   term("deliveryFee").tooltip     // شرحٌ مطوَّل
 */
export function term(key: TermKey): Term {
  return TERMS[key];
}


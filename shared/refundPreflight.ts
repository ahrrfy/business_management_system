/**
 * **عقدُ تمهيد الاسترداد** — الشاشةُ تسأل ولا تُخمّن.
 *
 * الشريحةُ الأولى بنت المنتقي على **تخمينٍ عميليّ** لما سيحتاجه الخادم (طريقةُ العربون،
 * `invoicePaidAmount`…). ومراجعةُ Codex على #920 أثبتت أنّ التخمين يُنتج **حوائطَ جديدة** —
 * وهو نقيضُ غاية الشريحة:
 *
 *  · أمرٌ مُسلَّمٌ مدفوعٌ **بالبطاقة** كاملاً: الشاشة تطلب درجاً، ولا وردية مفتوحة ⇒ **الزرّ
 *    معطَّلٌ فيستحيل الاسترجاع** — بينما الخادم لا يحتاج درجاً أصلاً لغير النقد.
 *  · طردٌ **بلا نقدٍ إطلاقاً**: نفس التعطيل على إرجاعٍ روتينيّ.
 *  · أمرٌ من **مسوّدة استقبال**: عربونُه في `orderPayments` لا في `workOrders.deposit`
 *    ⇒ الشاشة تُخفي المنتقي والخادمُ يطلبه ⇒ البابُ المسدود الأصليّ يعود.
 *
 * ⇒ **مصدرُ الحقيقة واحد: الخادم.** يُجيب عن الأسئلة الأربعة معاً — هل يخرج نقد؟ كم؟ من أيّ
 * فرع؟ وما الأدراج المؤهَّلة؟ — بالحسبة نفسها التي ستُنفَّذ فعلاً، فلا انحرافَ ممكنٌ بين ما
 * تعرضه الشاشة وما يقرّره الخادم.
 *
 * وبذلك تُغلق أيضاً ثغرتان بنيويّتان:
 *  · **الصلاحية**: الأدراج تأتي عبر بوّابة الوحدة المالكة (`workorders`/`store`) لا عبر
 *    `treasury:READ` — فدورٌ مخوَّلٌ للإلغاء وممنوعٌ من الخزينة لم يعد يرى قائمةً فارغة
 *    تُعطّل فعلَه نهائياً.
 *  · **عزلُ الفرع**: الأدراج مُصفّاةٌ خادمياً بفرع المستند ونوع الوردية — فلا يُعرَض على
 *    الأدمن درجُ فرعٍ آخر يرفضه الخادم بعد الاختيار.
 */

/** درجٌ مؤهَّلٌ فعلاً لهذه العملية — مُصفّى خادمياً بالفرع والنوع. */
export interface RefundDrawerCandidate {
  shiftId: number;
  userId: number;
  userName: string;
  shiftType: string;
  /**
   * النقدُ المتاح الآن بنفس صيغة `assertCashOutAvailable` — نصٌّ لا رقم (§٥).
   *
   * ⚠️ **يُحجَب عمّن لا يملك `treasury:READ`** (مراجعة Codex P2): هذه النقاطُ محروسةٌ ببوّابة
   * الفعل (`workorders`/`store`)، فدورٌ كـ`sales_rep` (بلا صندوق، `treasury:NONE`) كان يتلقّى
   * **أرصدةَ كلّ درجٍ مفتوحٍ بالفرع** — تجاوزٌ لعزل الأدراج المُقرَّر في تدقيق ٢/٧ (معرفةُ
   * أرصدة الزملاء لحظياً تُمكّن استهداف السرقة). المحجوبُ عنه يحصل على `sufficient` وحده.
   */
  expectedCash?: string;
  /**
   * أيكفي هذا الدرجُ المبلغَ المتوقَّع؟ — بديلٌ غيرُ حسّاس يُغني عن الرقم لمن لا يملك الخزينة:
   * يكفي لاختيارٍ صائب بلا كشفِ رصيد.
   */
  sufficient: boolean;
}

export interface RefundPreflight {
  /**
   * هل يخرج نقدٌ من درجٍ فعلاً؟ **محسوبٌ بمنطق العملية نفسه** لا بتقريبٍ عميليّ.
   * `false` ⇒ لا منتقيَ ولا حجبَ إطلاقاً، ولو لم تكن ثمّة وردية مفتوحة.
   */
  needsCashDrawer: boolean;
  /** المبلغُ المتوقّع خروجه نقداً — نصٌّ ماليّ (منزلتان)، صفرٌ حين لا نقد. */
  estimatedCashOut: string;
  /** فرعُ المستند — لا فرعُ المستخدم. */
  branchId: number;
  /** الأدراجُ المؤهَّلة (فارغةٌ ⇒ لا وردية مفتوحة تصلح لهذه العملية). */
  drawers: RefundDrawerCandidate[];
}

/** عمليّاتُ أمر الشغل التي قد تُخرج نقداً. */
export type WorkOrderRefundOperation = "CANCEL" | "REVERSE_DELIVERY";

/** تمهيدٌ محايدٌ يُستعمَل ريثما يصل الردّ — لا يحجب ولا يَعِد بشيء. */
export const EMPTY_REFUND_PREFLIGHT: RefundPreflight = {
  needsCashDrawer: false,
  estimatedCashOut: "0.00",
  branchId: 0,
  drawers: [],
};

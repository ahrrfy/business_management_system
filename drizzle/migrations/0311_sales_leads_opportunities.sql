CREATE TABLE IF NOT EXISTS `salesOpportunities` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `opportunityNumber` VARCHAR(50) NOT NULL,
  `branchId` BIGINT NOT NULL,
  `leadId` BIGINT NULL,
  `customerId` BIGINT NULL,
  `ownerId` INT NOT NULL,
  `title` VARCHAR(255) NOT NULL,
  `stage` ENUM('DISCOVERY','PROPOSAL','NEGOTIATION','WON','LOST') NOT NULL DEFAULT 'DISCOVERY',
  `expectedValue` DECIMAL(15,2) NOT NULL,
  `probability` DECIMAL(5,2) NOT NULL,
  `expectedCloseDate` DATE NOT NULL,
  `quotationId` BIGINT NULL,
  `invoiceId` BIGINT NULL,
  `lastReason` VARCHAR(500) NULL,
  `version` INT NOT NULL DEFAULT 1,
  `createKey` VARCHAR(120) NOT NULL,
  `createHash` CHAR(64) NOT NULL,
  `createdBy` INT NOT NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_sales_opp_number` (`opportunityNumber`),
  UNIQUE KEY `uq_sales_opp_create_key` (`createKey`),
  UNIQUE KEY `uq_sales_opp_lead` (`leadId`),
  UNIQUE KEY `uq_sales_opp_quotation` (`quotationId`),
  UNIQUE KEY `uq_sales_opp_invoice` (`invoiceId`),
  KEY `idx_sales_opp_branch_stage` (`branchId`, `stage`),
  KEY `idx_sales_opp_owner_close` (`ownerId`, `expectedCloseDate`),
  KEY `idx_sales_opp_customer` (`customerId`),
  CONSTRAINT `fk_sales_opp_branch` FOREIGN KEY (`branchId`) REFERENCES `branches` (`id`),
  CONSTRAINT `fk_sales_opp_lead` FOREIGN KEY (`leadId`) REFERENCES `salesLeads` (`id`),
  CONSTRAINT `fk_sales_opp_customer` FOREIGN KEY (`customerId`) REFERENCES `customers` (`id`),
  CONSTRAINT `fk_sales_opp_owner` FOREIGN KEY (`ownerId`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_sales_opp_quotation` FOREIGN KEY (`quotationId`) REFERENCES `quotations` (`id`),
  CONSTRAINT `fk_sales_opp_invoice` FOREIGN KEY (`invoiceId`) REFERENCES `invoices` (`id`),
  CONSTRAINT `fk_sales_opp_creator` FOREIGN KEY (`createdBy`) REFERENCES `users` (`id`),
  CONSTRAINT `chk_sales_opp_value_probability` CHECK (`expectedValue` >= 0 AND `probability` >= 0 AND `probability` <= 100),
  CONSTRAINT `chk_sales_opp_version` CHECK (`version` > 0),
  CONSTRAINT `chk_sales_opp_party` CHECK (`leadId` IS NOT NULL OR `customerId` IS NOT NULL),
  CONSTRAINT `chk_sales_opp_won_invoice` CHECK ((`stage` = 'WON' AND `invoiceId` IS NOT NULL) OR (`stage` <> 'WON' AND `invoiceId` IS NULL)),
  CONSTRAINT `chk_sales_opp_lost_reason` CHECK (`stage` <> 'LOST' OR `lastReason` IS NOT NULL)

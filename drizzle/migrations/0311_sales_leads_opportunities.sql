-- المساران مقصوران بالفرع، بنسخة تفاؤلية، ومفاتيح إعادة آمنة، وأحداث تراكمية بلا حذف صلب.

CREATE TABLE IF NOT EXISTS `salesLeads` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `leadNumber` VARCHAR(50) NOT NULL,
  `branchId` BIGINT NOT NULL,
  `source` ENUM('WALK_IN','PHONE','WHATSAPP','INSTAGRAM','FACEBOOK','WEBSITE','REFERRAL','CAMPAIGN','OTHER') NOT NULL,
  `contactName` VARCHAR(255) NOT NULL,
  `companyName` VARCHAR(255) NULL,
  `phone` VARCHAR(20) NULL,
  `email` VARCHAR(320) NULL,
  `customerId` BIGINT NULL,
  `ownerId` INT NOT NULL,
  `nextFollowUpAt` TIMESTAMP NULL,
  `status` ENUM('NEW','CONTACTED','QUALIFIED','DISQUALIFIED','CONVERTED') NOT NULL DEFAULT 'NEW',
  `lastReason` VARCHAR(500) NULL,
  `version` INT NOT NULL DEFAULT 1,
  `createKey` VARCHAR(120) NOT NULL,
  `createHash` CHAR(64) NOT NULL,
  `createdBy` INT NOT NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_sales_lead_number` (`leadNumber`),
  UNIQUE KEY `uq_sales_lead_create_key` (`createKey`),
  KEY `idx_sales_lead_branch_status` (`branchId`, `status`),
  KEY `idx_sales_lead_owner_followup` (`ownerId`, `nextFollowUpAt`),
  KEY `idx_sales_lead_customer` (`customerId`),
  CONSTRAINT `fk_sales_lead_branch` FOREIGN KEY (`branchId`) REFERENCES `branches` (`id`),
  CONSTRAINT `fk_sales_lead_customer` FOREIGN KEY (`customerId`) REFERENCES `customers` (`id`),
  CONSTRAINT `fk_sales_lead_owner` FOREIGN KEY (`ownerId`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_sales_lead_creator` FOREIGN KEY (`createdBy`) REFERENCES `users` (`id`),
  CONSTRAINT `chk_sales_lead_version` CHECK (`version` > 0),
  CONSTRAINT `chk_sales_lead_contact` CHECK (CHAR_LENGTH(TRIM(`contactName`)) > 0),
  CONSTRAINT `chk_sales_lead_disqualified_reason` CHECK (`status` <> 'DISQUALIFIED' OR `lastReason` IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

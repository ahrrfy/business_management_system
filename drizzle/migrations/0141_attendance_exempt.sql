-- 0141 — إعفاء موظفٍ من الحضور (راتب ثابت)
--
-- قرار المالك (٣١/٧): «لديّ موظفون ليس لديهم بصمة حضور وانصراف، فقط رواتب. وأنا وأخي
-- مالكو الشركة ليس لدينا بصمة».
--
-- **الخطر المُثبَت**: مع تفعيل الأجر بالحضور، موظفٌ بلا بصمات يُحتسب ٢٦ يوم غياب
-- فيقبض **صفراً** من راتبٍ مليون. تفعيل الخاصية كان سيُصفّر رواتب المُلّاك وكل من لا
-- جهاز له في أول مسيّر.
--
-- العلَم **صريح لا مُخمَّن**: لو أُعفي «من لا بصمات له» تلقائياً، لأُعفي صامتاً موظفٌ
-- مربوطٌ تعطّل جهازه شهراً فقبض راتباً كاملاً عن غيابٍ حقيقيّ. والافتراضي **خاضع**
-- (قرار المالك) فالإعفاء استثناءٌ يُقرَّر لا قاعدة تُنسى.
--
-- الإعفاء من **الحضور وحده**: الإجازات والسلف والعمولات تبقى تعمل كما هي (قرار المالك).


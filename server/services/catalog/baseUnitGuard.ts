import { TRPCError } from "@trpc/server";
import { and, desc, eq } from "drizzle-orm";
import { productUnits } from "../../../drizzle/schema";
import type { Tx } from "../../db";

/**
 * وحدة الأساس الجديدة المقصودة — تُعرَّف إمّا بمعرّف صفّها المُرسَل (المسار الحامل للمعرّفات
 * `catalog/productUpdate`، الذي يُحدِّث الوحدة بالمعرّف فيُعيد تسميتها **في مكانها**) أو باسمها (مسار
 * القالب المشترك `productEditService`، حيث `upsertVariantUnits` يطابق بالاسم فيُدرِج صفّاً جديداً
 * ويُعطّل القديم عند تغيّر الاسم). أحدهما يكفي؛ يُفضَّل المعرّف حين يتوفّر.
 */
export type IntendedBase = { unitId?: number | null; unitName?: string | null };

/**
 * حارس ثبات وحدة الأساس (تدقيق ١١/٨ — بعد ثلاث جولات مراجعة Codex العدائية).
 *
 * الأرصدة والحركات والوصفات (bundleComponents) والحجوزات (reservationStock) وأوامر الشراء وبنود
 * الفواتير/العروض/الطلبات كلّها مخزَّنة أو مرتبطة **بالوحدة الأساس** — إمّا كمّيةً مُقوَّمةً بالأساس
 * (branchStock/inventoryMovements/componentBaseQuantity/reservedBase/baseQuantity/…) أو معرّفَ وحدةٍ
 * (productUnitId) يُشير إلى صفّ الأساس (بنود العروض والطلبات المعلّقة). لذا تغيير **هويّة** وحدة الأساس
 * لمتغيّرٍ قائم — سواء بترقية صفٍّ آخر إلى الأساس (تبديل) أو بإعادة تسميةٍ تُدرِج صفّاً جديداً وتُعطّل
 * القديم (المسار الوحيد الذي يملكه `upsertVariantUnits` عند تغيّر الاسم) — إمّا يعيد تفسير تلك الكمّيات
 * صامتاً (١٤٤ قطعة تصير ١٤٤ درزناً) أو يُدلّي معرّفات الوحدة في العروض/الطلبات المعلّقة فيتعذّر تنفيذها.
 *
 * جولات Codex الثلاث برهنت أنّ حصر «كل مخزنٍ مُقوَّمٍ بالأساس» غير مكتملٍ أبداً (رصيد ← حركات ← بكج ←
 * حجز ← أمر شراء ← بند فاتورة خدمةٍ بلا حركة ← عرضٌ/طلبٌ معلّق…) وأنّ قراءة تلك الحالة المتغيّرة تحت
 * التزامن تفتح سباقاتٍ لا تنتهي (كلٌّ يقفل جدوله فلا تسلسل). فالحلّ **الأبسط والأمتن والأعلى قيمة**:
 * وحدة الأساس **ثابتةٌ** لمتغيّرٍ قائمٍ له أساسٌ نشط — لا تتبدّل هويّتُها ولا اسمُها عبر التعديل. الكشف
 * **مقارنةٌ ساكنةٌ لصفّ الأساس وحده** (لا قراءةَ حالةٍ متغيّرة ⇒ **لا حاجة لأيّ قفلٍ ولا سباقٍ ولا حصرٍ
 * يتقادم**، والتعديل لا يكتسب أيّ قفل branchStock فيسقط خطر الجمود المتقاطع مع البيع)، والتصحيح بإنشاء
 * متغيّرٍ جديدٍ بالوحدة الصحيحة. متغيّرٌ بلا أساسٍ نشطٍ بعد (جديدٌ تماماً) يُسمح بتثبيت أساسه أوّل مرّة.
 *
 * ملاحظة الأسلوب: المسار الحامل للمعرّف يُعيد تسمية صفّ الأساس **في مكانه** (نفس المعرّف)، فإعادة
 * التسمية هناك آمنةٌ (الصفّ يبقى، مراجعه سليمة، ومعناه بمِعامل ١ ثابت) والحارس يسمح بها؛ أمّا مسار
 * القالب فلا يملك إعادة تسميةٍ في مكانها (يطابق بالاسم)، فأيّ اسمٍ جديدٍ للأساس تبديلٌ يُرفَض.
 *
 * يُستدعى من **كلا** مساري التعديل كي لا يتسرّب التغيير عبر المسار القديم.
 */
export async function assertBaseUnitStable(tx: Tx, variantId: number, intended: IntendedBase): Promise<void> {
  const vid = Number(variantId);
  if (!Number.isInteger(vid) || vid <= 0) return;

  // صفّ الأساس المرجعيّ: نُفضّل النشط، وإلّا فأحدث صفّ أساسٍ مُعطَّل (Codex جولة٤ P1) — فالأرصدة/الحركات
  // تبقى مُقوَّمةً بالأساس **حتى لو عُطِّل صفّه**؛ فمتغيّرٌ برصيدٍ وأساسٍ معطَّلٍ ليس «جديداً». يُعتبَر جديداً
  // (فيُسمح بتثبيت أساسه) فقط إن لم يكن له صفّ أساسٍ إطلاقاً (لا نشطٌ ولا معطَّل).
  const curBase = (
    await tx
      .select({ id: productUnits.id, name: productUnits.unitName })
      .from(productUnits)
      .where(and(eq(productUnits.variantId, vid), eq(productUnits.isBaseUnit, true)))
      .orderBy(desc(productUnits.isActive), desc(productUnits.id))
      .limit(1)
  )[0];
  if (!curBase) return; // لا صفّ أساسٍ إطلاقاً ⇒ متغيّرٌ جديدٌ تماماً ⇒ يُسمح بتثبيت أساسه أوّل مرّة.

  // تغيّرت هويّة الأساس؟
  //  • المسار الحامل للمعرّف: معرّفٌ مختلفٌ عن صفّ الأساس الحاليّ (أو صفٌّ جديدٌ id=null) ⇒ تبديل.
  //    نفس المعرّف (ولو باسمٍ جديد) = إعادة تسميةٍ في مكانها ⇒ آمنة.
  //  • مسار القالب: يطابق `upsertVariantUnits` القالبَ بالقائم بـ`unitName === name.trim()` (اسمٌ مقصوصٌ
  //    مُرسَل مقابل اسمٍ مخزَّنٍ **خام**، بلا قصٍّ للمخزَّن — Codex جولة٤ P2)؛ فيُبقي صفّ الأساس أساساً فقط إن
  //    ساوى الاسمُ المخزَّن الخام الاسمَ المُرسَل المقصوص. نطابق دلالته حرفاً (لا نقصّ المخزَّن) وإلّا مرّ
  //    اسمٌ مخزَّنٌ بمسافةٍ زائدةٍ من الحارس بينما يستبدله المُحدِّث فتتدلّى مراجع productUnitId.
  const changed =
    intended.unitId != null
      ? Number(intended.unitId) !== Number(curBase.id)
      : (curBase.name ?? "") !== (intended.unitName ?? "").trim();
  if (!changed) return;

  throw new TRPCError({
    code: "BAD_REQUEST",
    message:
      "لا يمكن تبديل وحدة الأساس أو إعادة تسميتها لمتغيّرٍ قائم — كلّ الأرصدة والحركات والحجوزات وأوامر الشراء والعروض/الطلبات مخزَّنة أو مرتبطة بالوحدة الأساس، فتغييرها يُفسد تفسيرها أو يُدلّي مراجعها. أنشئ متغيّراً جديداً بالوحدة الصحيحة بدل التغيير.",
  });
}
